from pathlib import Path
from typing import Any
import os
from src.utils.naming import case_name

def write_run_script(
    output_dir: Path,
    cases: list[dict[str, Any]],
    container_base_dir: str,
    max_jobs: int = 3,
) -> Path:
    script_path = output_dir / "run_all_openfoam.sh"
    n = len(cases)

    with open(script_path, "w") as f:
        f.write("#!/bin/bash\n")
        f.write("# Parallel OpenFOAM runner — generated by write_run_script\n")
        f.write("# Run INSIDE OpenFOAM Docker container\n\n")
        f.write("set -euo pipefail\n\n")
        f.write(f'BASE_DIR="{container_base_dir}"\n')
        f.write(f'MAX_JOBS={max_jobs}\n')
        f.write('LOG_DIR="$BASE_DIR/parallel_logs"\n')
        f.write('DONE_FILE="$BASE_DIR/.completed_cases"\n')
        f.write('FAIL_FILE="$BASE_DIR/.failed_cases"\n\n')
        f.write('mkdir -p "$LOG_DIR"\n')
        f.write('touch "$DONE_FILE" "$FAIL_FILE"\n\n')

        # Case name array
        f.write("declare -A CASE_NAMES\n")
        for idx, p in enumerate(cases, start=1):
            name = case_name(p, idx)
            f.write(f'CASE_NAMES[{idx}]="{name}"\n')
        f.write("\n")

        # run_one_case function
        f.write('run_one_case() {\n')
        f.write('    local ID=$1\n')
        f.write('    local PADDED=$(printf "%03d" "$ID")\n')
        f.write('    local NAME="${CASE_NAMES[$ID]}"\n')
        f.write('    local CASE_DIR="$BASE_DIR/$NAME"\n')
        f.write('    local LOG="$LOG_DIR/${PADDED}_${NAME}.log"\n')
        f.write('    local T0=$(date +%s)\n\n')
        f.write('    [[ ! -d "$CASE_DIR" ]] && echo "MISSING [$PADDED]: $CASE_DIR" && return 1\n\n')
        f.write('    echo "  START [$PADDED]: $NAME"\n')
        f.write('    {\n')
        f.write('        cd "$CASE_DIR"\n')
        f.write('        bash Allmesh\n')
        f.write('        bash Allrun\n')
        f.write('        foamToVTK -allRegions\n')
        f.write('    } > "$LOG" 2>&1\n\n')
        f.write('    local EC=$?  T1=$(date +%s)\n')
        f.write('    local MM=$(( (T1-T0)/60 )) SS=$(( (T1-T0)%60 ))\n\n')
        f.write('    if [[ $EC -eq 0 ]]; then\n')
        f.write('        echo "  DONE  [$PADDED] (${MM}m${SS}s): $NAME"\n')
        f.write('        echo "$PADDED" >> "$DONE_FILE"\n')
        f.write('    else\n')
        f.write('        echo "  FAIL  [$PADDED] (${MM}m${SS}s): $NAME"\n')
        f.write('        tail -5 "$LOG" | sed "s/^/         /"\n')
        f.write('        echo "$PADDED FAILED $NAME" >> "$FAIL_FILE"\n')
        f.write('        return 1\n')
        f.write('    fi\n')
        f.write('}\n\n')

        f.write('export BASE_DIR LOG_DIR DONE_FILE FAIL_FILE\n')
        f.write('export -f run_one_case\n\n')

        # Parallel scheduler
        f.write(f'PIDS=(); IDS=(); FAILED=0\n\n')
        f.write(f'for ID in $(seq 1 {n}); do\n')
        f.write('    # Wait for a free slot\n')
        f.write('    while [[ ${#PIDS[@]} -ge $MAX_JOBS ]]; do\n')
        f.write('        NEW_PIDS=(); NEW_IDS=()\n')
        f.write('        for i in "${!PIDS[@]}"; do\n')
        f.write('            P=${PIDS[$i]}\n')
        f.write('            if kill -0 "$P" 2>/dev/null; then\n')
        f.write('                NEW_PIDS+=("$P"); NEW_IDS+=("$ID")\n')
        f.write('            else\n')
        f.write('                wait "$P" && EC=0 || EC=$?\n')
        f.write('                [[ $EC -ne 0 ]] && (( FAILED++ )) || true\n')
        f.write('            fi\n')
        f.write('        done\n')
        f.write('        PIDS=("${NEW_PIDS[@]}"); IDS=("${NEW_IDS[@]}")\n')
        f.write('        [[ ${#PIDS[@]} -ge $MAX_JOBS ]] && sleep 3\n')
        f.write('    done\n\n')
        f.write('    ( run_one_case "$ID" ) &\n')
        f.write('    PIDS+=($!); IDS+=("$ID")\n')
        f.write('    echo "  LAUNCH [$ID] PID=$!  (${#PIDS[@]}/$MAX_JOBS slots)"\n')
        f.write('done\n\n')

        f.write('echo "Waiting for last ${#PIDS[@]} job(s)..."\n')
        f.write('for P in "${PIDS[@]}"; do\n')
        f.write('    wait "$P" && EC=0 || EC=$?\n')
        f.write('    [[ $EC -ne 0 ]] && (( FAILED++ )) || true\n')
        f.write('done\n\n')

        f.write('echo ""\n')
        f.write(f'echo "All {n} cases done. Failed: $FAILED"\n')
        f.write('[[ $FAILED -gt 0 ]] && exit 1 || exit 0\n')

    os.chmod(script_path, 0o755)
    return script_path