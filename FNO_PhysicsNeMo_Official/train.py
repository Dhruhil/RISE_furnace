"""
3D FNO training — predicts T_next directly (normalised, full field
not delta).

8-channel voxel input, region-weighted data loss, pushforward
regularisation, and a gentle physics-informed regulariser on top.

Why physics is a *regulariser* and not a hard constraint here:
  The dataset itself is generated by OpenFOAM, which already solves
  the full Navier-Stokes + heat equations on every cell. The data
  contains the physics — the FNO just has to learn the operator
  that maps it forward in time. So the physics term doesn't carry
  the run; it nudges the model toward energy-balance-consistent
  predictions during the long autoregressive rollout, which keeps
  Phase-2 errors from blowing up.
"""
